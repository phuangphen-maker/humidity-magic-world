export const KEY = "humidity-magic-world:v1";
export function fresh(profile) {
  return {
    profile,
    level: 0,
    answered: [],
    coins: [],
    missions: [],
    checkpoint: 0,
    completed: false,
  };
}
export const score = (s) => s.answered.length * 10;
export function answer(s, id) {
  if (!s.answered.includes(id)) s.answered.push(id);
  return score(s);
}
export function validSave(s) {
  return (
    s &&
    s.profile &&
    typeof s.profile.name === "string" &&
    Number.isInteger(s.level) &&
    s.level >= 0 &&
    s.level < 7 &&
    Array.isArray(s.answered) &&
    s.answered.every((id) => Number.isInteger(id) && id >= 0 && id < 21) &&
    new Set(s.answered).size === s.answered.length &&
    Array.isArray(s.coins) &&
    Array.isArray(s.missions)
  );
}
